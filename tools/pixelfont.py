def text_mask(text, spacing=1):
    """Boolean grid (7 rows) for the text, one cell per font pixel."""
    cols = []
    for i, ch in enumerate(text.upper()):
        g = GLYPHS[ch]
        w = len(g[0])
        for x in range(w):
            cols.append([g[y][x] == "#" for y in range(7)])
        if i < len(text) - 1:
            cols.extend([[False] * 7] * spacing)
    return np.array(cols, bool).T
